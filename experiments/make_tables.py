"""Generate the paper's tables from finished runs: `paper/tables/*.md` and `*.tex`.

`docs/08` section 6 says tables are generated, never typed by hand, and hard rule 2
says every number in one must come from a file under `experiments/results/`. This
script is how both are kept: it reads only the small summary files a run leaves
behind (`summary*.csv`, which are committed), formats them, and writes each table
twice - Markdown to read, LaTeX for the paper. It computes nothing new; a number
that is not already in a summary file cannot appear in a table.

Tables written so far (task M3.3):

* **Table 1** - the datasets: cases per system and fault type.
* **Table 2** - E1 grounding: ExpAC@1/3/5 and the symptom rate per method, pooled
  over RE1 and per system.
* **Table 2b** - E1's secondary, loose indicator score, per system and fault type
  with the size of the acceptable set beside it (`docs/08` section 4 says it must
  never be pooled into one number).

Tables 3 to 6 belong to later experiments and are added with them.

    analyzer/.venv/Scripts/python.exe experiments/make_tables.py
"""

from __future__ import annotations

import argparse
from collections.abc import Callable, Sequence
from dataclasses import dataclass
from pathlib import Path

import pandas as pd

REPO = Path(__file__).resolve().parents[1]

# The order methods appear in, and the plain name a reader of the paper sees. The
# engine name stays in brackets so a row can be traced to the code that made it.
METHODS: dict[str, str] = {
    "SHAP_IFOREST": "Isolation Forest + TreeSHAP",
    "PCA_RECON": "PCA reconstruction error",
    "ECDF": "ECDF tail score (ECOD-style)",
    "PARE_NO_RESIDUAL": "Robust z-score (PARE without residuals)",
}

SYSTEMS: dict[str, str] = {
    "online-boutique": "Online Boutique",
    "sock-shop": "Sock Shop",
    "train-ticket": "Train Ticket",
}

FAULTS = ("CPU", "MEM", "DISK", "DELAY", "LOSS")


@dataclass(frozen=True)
class Table:
    """One table, independent of how it is printed."""

    name: str
    title: str
    header: tuple[str, ...]
    rows: list[tuple[str, ...]]
    notes: tuple[str, ...]
    source: str

    def markdown(self) -> str:
        lines = [
            f"<!-- Generated by experiments/make_tables.py from {self.source}. "
            "Do not edit by hand. -->",
            "",
            f"**{self.title}**",
            "",
            "| " + " | ".join(self.header) + " |",
            "|" + "|".join("---" for _ in self.header) + "|",
        ]
        lines += ["| " + " | ".join(row) + " |" for row in self.rows]
        lines += [""] + [f"- {note}" for note in self.notes]
        return "\n".join(lines) + "\n"

    def latex(self) -> str:
        align = "l" + "r" * (len(self.header) - 1)
        lines = [
            f"% Generated by experiments/make_tables.py from {self.source}.",
            "% Do not edit by hand.",
            "\\begin{table}[t]",
            "\\centering",
            f"\\caption{{{_tex(self.title)}}}",
            f"\\label{{tab:{self.name}}}",
            "\\small",
            f"\\begin{{tabular}}{{{align}}}",
            "\\toprule",
            " & ".join(_tex(cell) for cell in self.header) + " \\\\",
            "\\midrule",
        ]
        for row in self.rows:
            if all(cell == "" for cell in row[1:]):
                # A section heading inside the table (a system name).
                lines.append(
                    f"\\multicolumn{{{len(self.header)}}}{{l}}{{\\textit{{{_tex(row[0])}}}}} \\\\"
                )
            else:
                lines.append(" & ".join(_tex(cell) for cell in row) + " \\\\")
        lines += ["\\bottomrule", "\\end{tabular}"]
        if self.notes:
            lines.append("\\par\\smallskip\\footnotesize")
            lines += [_tex(note) + "\\par" for note in self.notes]
        lines.append("\\end{table}")
        return "\n".join(lines) + "\n"


# --- the tables -------------------------------------------------------------


def table1_datasets(e1: Path) -> Table:
    """Cases per system and fault type, read off the E1 run that used them."""
    frame = pd.read_csv(e1 / "summary_by_system_fault.csv")
    # Every method saw the same cases, so one method's counts are the dataset's.
    one = frame[frame["method"] == frame["method"].iloc[0]]
    rows: list[tuple[str, ...]] = []
    for system, label in SYSTEMS.items():
        part = one[one["system"] == system].set_index("fault_type")
        if part.empty:
            continue
        counts = [int(part.loc[fault, "cases"]) if fault in part.index else 0 for fault in FAULTS]
        rows.append((label, *map(str, counts), str(sum(counts))))
    totals = [sum(int(row[i + 1]) for row in rows) for i in range(len(FAULTS) + 1)]
    rows.append(("Total", *map(str, totals)))
    return Table(
        name="datasets",
        title="Table 1. RCAEval RE1 cases used, per system and fault type",
        header=("System", *FAULTS, "Total"),
        rows=rows,
        notes=(
            "Five broken services per system, five repetitions each. Metrics only: "
            "RE1 carries no logs or traces.",
            "Indicator ground truth is unambiguous for CPU and MEM only; DISK, DELAY "
            "and LOSS have no metric of their own (docs/08 section 4).",
        ),
        source=_relative(e1 / "summary_by_system_fault.csv"),
    )


def table2_grounding(e1: Path) -> Table:
    """E1's main table: does the explanation name the right metric?"""
    overall = pd.read_csv(e1 / "summary.csv").set_index("method")
    by_system = pd.read_csv(e1 / "summary_by_system.csv")

    header = (
        "Method",
        "ExpAC@1",
        "ExpAC@3",
        "ExpAC@5",
        "AC@1",
        "AC@1, CPU+MEM",
        "Gap",
        "Symptom rate",
        "Chance",
        "ms / case",
    )

    def row(label: str, data: pd.Series) -> tuple[str, ...]:
        return (
            label,
            _num(data["exp_ac1"]),
            _num(data["exp_ac3"]),
            _num(data["exp_ac5"]),
            _num(data["ac1"]),
            _num(data["ac1_strict"]),
            _num(float(data["ac1_strict"]) - float(data["exp_ac1"])),
            _num(data["symptom_rate"]),
            _num(data["symptom_chance"]),
            f"{float(data['mean_ms']):.0f}",
        )

    rows: list[tuple[str, ...]] = [(f"All of RE1 ({_cases(overall)} cases)", *[""] * 9)]
    rows += [row(label, overall.loc[method]) for method, label in _present(overall.index)]
    for system, system_label in SYSTEMS.items():
        part = by_system[by_system["system"] == system].set_index("method")
        if part.empty:
            continue
        rows.append((f"{system_label} ({_cases(part)} cases)", *[""] * 9))
        rows += [row(label, part.loc[method]) for method, label in _present(part.index)]

    strict = int(overall["strict_cases"].iloc[0])
    return Table(
        name="e1_grounding",
        title="Table 2. E1: do explanations name the root-cause indicator (ExpAC@k) "
        "and, when wrong, do they blame a symptom?",
        header=header,
        rows=rows,
        notes=(
            f"ExpAC@k is strict: the {strict} CPU and MEM cases of all of RE1 "
            "(50 per system), where the right metric is the one the fault stressed. "
            "AC@1 is the coarse question, the right service, over every case; "
            "'AC@1, CPU+MEM' is the same over the strict cases only, and Gap is it "
            "minus ExpAC@1 - right service, wrong metric - on identical cases.",
            "Symptom rate: of the wrong top-1 answers, the share that blamed a "
            "service which calls the real culprit. Chance: the same rate for a wrong "
            "answer picked at random among the ranked services. Read the rate "
            "against it.",
            "No call graph exists yet for Train Ticket (built from RE2 traces in a "
            "later task), so its symptom rate is empty and the pooled rate covers "
            "Online Boutique and Sock Shop only.",
            "Ties are scored as the expected value under a random order of the tied "
            "group, for AC@k, ExpAC@k and the symptom rate alike (docs/08 section 4).",
            "Detection delay 0 s. ms / case is wall time on a 10-core laptop with "
            "cases run in parallel, so it compares methods, not absolute speed.",
        ),
        source=_relative(e1),
    )


def table2b_loose(e1: Path) -> Table:
    """The secondary indicator score, never pooled across fault types."""
    frame = pd.read_csv(e1 / "summary_by_system_fault.csv")
    methods = [method for method, _ in _present(frame["method"].unique())]
    header = ("System / fault", "Acceptable metrics", *[METHODS[m] for m in methods])

    rows: list[tuple[str, ...]] = []
    for system, label in SYSTEMS.items():
        part = frame[frame["system"] == system]
        if part.empty:
            continue
        rows.append((label, *[""] * (len(header) - 1)))
        for fault in FAULTS:
            cells = part[part["fault_type"] == fault].set_index("method")
            if cells.empty:
                continue
            size = str(cells["acceptable_indicators"].iloc[0])
            rows.append(
                (fault, size, *[_num(cells.loc[m, "exp_ac1_loose"]) for m in methods])
            )
    return Table(
        name="e1_loose",
        title="Table 2b. E1, secondary: loose ExpAC@1 per fault type",
        header=header,
        rows=rows,
        notes=(
            "A hit when the top indicator is any metric in the fault type's "
            "acceptable set; the set's size is in the second column, and a larger "
            "set is an easier question.",
            "Reported per fault type only, never pooled: averaging a 1-metric "
            "question with a 4-metric one would mean nothing (docs/08 section 4).",
            "For CPU and MEM the set holds one metric, so these rows equal the "
            "strict score.",
        ),
        source=_relative(e1 / "summary_by_system_fault.csv"),
    )


TABLES: dict[str, Callable[[Path], Table]] = {
    "table1_datasets": table1_datasets,
    "table2_e1_grounding": table2_grounding,
    "table2b_e1_loose": table2b_loose,
}


# --- helpers ----------------------------------------------------------------


def _present(methods: Sequence[str]) -> list[tuple[str, str]]:
    """Known methods in display order, then any unknown ones under their own
    name, so a new engine in a run is shown rather than silently dropped."""
    available = set(methods)
    ordered = [(m, f"{label} [{m}]") for m, label in METHODS.items() if m in available]
    ordered += [(m, m) for m in sorted(available - set(METHODS))]
    return ordered


def _cases(frame: pd.DataFrame) -> int:
    return int(frame["cases"].iloc[0])


def _num(value: object) -> str:
    """Three decimals; an empty cell for a value that does not exist (no graph,
    nothing wrong), rather than a 0 that would read as a measurement."""
    if value is None or (isinstance(value, float) and pd.isna(value)) or value == "":
        return ""
    return f"{float(value):.3f}"


def _tex(text: str) -> str:
    for char, escaped in (("\\", "\\textbackslash{}"), ("&", "\\&"), ("%", "\\%"),
                          ("_", "\\_"), ("#", "\\#"), ("$", "\\$")):
        text = text.replace(char, escaped)
    return text


def _relative(path: Path) -> str:
    try:
        return path.resolve().relative_to(REPO).as_posix()
    except ValueError:
        return path.as_posix()


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--e1", type=Path, default=REPO / "experiments" / "results" / "e1_re1",
                        help="the pooled E1 run folder")
    parser.add_argument("--out", type=Path, default=REPO / "paper" / "tables")
    args = parser.parse_args(argv)

    args.out.mkdir(parents=True, exist_ok=True)
    for name, build in TABLES.items():
        table = build(args.e1)
        (args.out / f"{name}.md").write_text(table.markdown(), encoding="utf-8", newline="\n")
        (args.out / f"{name}.tex").write_text(table.latex(), encoding="utf-8", newline="\n")
        print(f"wrote {name}.md and {name}.tex")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
